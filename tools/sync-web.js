// Copies the shared pieces of the extension into docs/ (the mobile web app) so there is one source of truth.
// Run from the repo root:  node tools/sync-web.js
const fs = require("fs");
const src = fs.readFileSync("content.js", "utf8");
const cut = (from, to) => {
  const a = src.indexOf(from), b = src.indexOf(to, a);
  if (a < 0 || b < 0) throw new Error("marker not found: " + from);
  return src.slice(a, b);
};
const parser = cut("const TIME =", "// ---------- Player control");
const prompts = cut("const PROMPTS = {", "async function copyPrompt");
const core = `// GENERATED by tools/sync-web.js from content.js. Do not edit by hand.
(() => {
  const pad = (n) => String(n).padStart(2, "0");
  const toSec = (t) => t.split(":").reduce((a, x) => a * 60 + Number(x), 0);
  const video = () => ({ duration: self.__dur || 0 });
  ${parser}
  ${prompts}
  self.Core = { parseBlocks, PROMPTS, TAILS };
})();
`;
fs.writeFileSync("docs/core.js", core);
fs.copyFileSync("shared.js", "docs/shared.js");
for (const f of ["icon128.png"]) fs.copyFileSync("icons/" + f, "docs/icons/" + f);
console.log("synced docs/core.js, docs/shared.js");
