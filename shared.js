  // Merge a stored config over the defaults (also migrates the 0.2/0.3 shape).
  function mergeCfg(c) {
    const d = structuredClone(DEFAULT_CFG);
    if (!c) return d;
    const out = { ...d, ...c };
    out.speed = { ...d.speed, ...c.speed };
    out.r3 = { ...d.r3, ...c.r3 };
    out.langs = { ...d.langs, ...c.langs };
    // 0.4.x kept separate bars per site; now one pair applies everywhere (hard-coded subtitles belong to the video, not the site).
    const old = c.bars && (c.bars.youtube || c.bars.netflix) ? c.bars.youtube || c.bars.netflix : c.bars;
    out.bars = { ...d.bars, ...(old && typeof old.top === "number" ? { top: old.top, bottom: old.bottom } : {}) };
    if (c.maskH != null && !c.bars) out.bars.bottom = c.maskH;
    if (c.lang && !c.uiLang) out.uiLang = c.lang;
    if (!UI[out.uiLang]) out.uiLang = "en";
    delete out.maskH; delete out.lang;
    return out;
  }
  const makeT = (uiLang) => (k, ...a) => {
    const s = (UI[uiLang] && UI[uiLang][k]) ?? UI.en[k] ?? k;
    return s.replace(/\{(\d+)\}/g, (_, i) => a[+i]);
  };
  const codeOf = (name) => {
    const n = String(name || "").trim().toLowerCase();
    const f = LANGS.find(([c, en, nat]) => en.toLowerCase() === n || nat.toLowerCase() === n || c === n);
    return f ? f[0] : null;
  };

  self.YR = { LANGS, UI_LANGS, UI, DEFAULT_CFG, mergeCfg, makeT, codeOf };
